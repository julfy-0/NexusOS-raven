#!/usr/bin/env python3
"""
convert_wallpaper.py — конвертация обоев PNG → RGB565 header для NexusOS bare-metal.
Масштабирует wall1.png до 360×780 (четверть 1440×3040) для экономии места.
Выход: wallpaper_data.h с массивом uint16_t wallpaper_rgb565[].
"""
from PIL import Image

SRC = '/mnt/c/Dev/NexusOS-P6P/assets/wallpapers/wall1.png'
DST_H = '/mnt/c/Dev/NexusOS-P6P/kernel/drivers/gpu/gs101/wallpaper_data.h'
# Уменьшаем в 4 раза (будет растянут при рисовании)
W, H = 360, 780

img = Image.open(SRC).convert('RGB').resize((W, H), Image.LANCZOS)
pixels = list(img.getdata())

with open(DST_H, 'w') as f:
    f.write('/* Auto-generated by convert_wallpaper.py — DO NOT EDIT */\n')
    f.write('#ifndef NEXUS_WALLPAPER_DATA_H\n')
    f.write('#define NEXUS_WALLPAPER_DATA_H\n')
    f.write('#include <stdint.h>\n\n')
    f.write(f'#define WALLPAPER_W {W}\n')
    f.write(f'#define WALLPAPER_H {H}\n\n')
    f.write(f'static const uint16_t wallpaper_rgb565[{W * H}] = {{\n')
    for i, (r, g, b) in enumerate(pixels):
        rgb565 = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        f.write(f'0x{rgb565:04X}')
        if i < len(pixels) - 1:
            f.write(',')
        if (i + 1) % 16 == 0:
            f.write('\n')
    f.write('\n};\n')
    f.write('#endif\n')

print(f'Written {W}x{H} = {W*H} pixels to {DST_H}')
print(f'File size: ~{W*H*2//1024} KB')
