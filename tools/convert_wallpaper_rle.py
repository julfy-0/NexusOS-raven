#!/usr/bin/env python3
"""
convert_wallpaper_rle.py — конвертация wall1.png → RLE RGB565 header для NexusOS.
Использует простое RLE: [count, pixel] пары uint16_t.
180x390 пикселей для минимального размера (~100KB header).
"""
from PIL import Image

SRC = '/mnt/c/Dev/NexusOS-P6P/assets/wallpapers/wall1.png'
DST_H = '/mnt/c/Dev/NexusOS-P6P/kernel/drivers/gpu/gs101/wallpaper_data.h'
W, H = 180, 390  # будет bilinear stretch x8 на 1440x3040

img = Image.open(SRC).convert('RGB').resize((W, H), Image.LANCZOS)
pixels = []
for y in range(H):
    for x in range(W):
        r, g, b = img.getpixel((x, y))
        rgb565 = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        pixels.append(rgb565)

# RLE encode
runs = []
i = 0
while i < len(pixels):
    cur = pixels[i]
    count = 1
    while i + count < len(pixels) and pixels[i + count] == cur and count < 255:
        count += 1
    runs.append((count, cur))
    i += count

total_runs = len(runs)
print(f'Raw pixels: {len(pixels)}, RLE runs: {total_runs}, ratio: {len(pixels)/total_runs:.1f}x')

with open(DST_H, 'w') as f:
    f.write('/* Auto-generated by convert_wallpaper_rle.py — DO NOT EDIT */\n')
    f.write('#ifndef NEXUS_WALLPAPER_DATA_H\n')
    f.write('#define NEXUS_WALLPAPER_DATA_H\n')
    f.write('#include <stdint.h>\n\n')
    f.write(f'#define WALLPAPER_W {W}\n')
    f.write(f'#define WALLPAPER_H {H}\n')
    f.write(f'#define WALLPAPER_RLE_RUNS {total_runs}\n\n')
    f.write('/* [count, rgb565] pairs — count in [1..255] */\n')
    f.write(f'static const uint16_t wallpaper_rle[{total_runs * 2}] = {{\n')
    for i, (cnt, px) in enumerate(runs):
        f.write(f'{cnt},0x{px:04X}')
        if i < len(runs) - 1:
            f.write(',')
        if (i + 1) % 8 == 0:
            f.write('\n')
    f.write('\n};\n')
    f.write('#endif\n')

import os
sz = os.path.getsize(DST_H)
print(f'Written {total_runs} runs to {DST_H} ({sz//1024} KB)')
